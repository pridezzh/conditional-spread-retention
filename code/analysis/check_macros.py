"""Pre-build check: are all macros referenced in the body defined by the numeric
macro files?

Numeric macro files (see NUM_FILES): after the third-round rewrite the body only
references numbers_theory.tex, generated by code/analysis/make_theory_macros.py
from logs/ and results/; numbers.tex is legacy from an older version (no longer
\\input by main.tex).

Motivation: every number in main.tex is referenced via a \\newcommand macro. If
even one macro is undefined (e.g. a statistic that is NaN under the current data
and skipped by the generation script), pdflatex reports "Undefined control
sequence" and stops far away, making debugging very costly. This script surfaces
the problem before the build and prints the missing list directly.

It also reverse-checks for macros that are defined but never referenced in the
body (dead macros), to avoid the illusion that "all numbers made it into the
paper" when in fact none were used.

Usage:
  python check_macros.py            # report only
  python check_macros.py --strict   # exit code 1 if any are missing (for CI / pipelines)
"""
