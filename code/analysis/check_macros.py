def read(path):
    with io.open(path, "r", encoding="utf-8", errors="replace") as f:
        return f.read()


def strip_comments(s):
    out = []
    for line in s.splitlines():
        # drop everything after an unescaped %
        buf, i = [], 0
        while i < len(line):
            c = line[i]
            if c == "\\" and i + 1 < len(line):
                buf.append(line[i:i + 2])
                i += 2
                continue
            if c == "%":
                break
            buf.append(c)
            i += 1
        out.append("".join(buf))
    return "\n".join(out)


def defined_macros():
    """Collect all "defined" control sequences.

    Looking only at numbers.tex is insufficient: main.tex's own preamble defines
    \\cD \\cL \\tr \\Var \\Cov \\Eop \\Ncal \\Real \\todo, and the ICLR template's
    math_commands.tex defines a large batch more. Omitting them would misreport
    normal references as missing.
    """
    sources = [os.path.join(PAPER, "main.tex"),
               os.path.join(PAPER, "iclr2027", "math_commands.tex")]
    sources += [os.path.join(PAPER, f) for f in NUM_FILES]
    defs, nums = set(), set()
    for p in sources:
        if not os.path.isfile(p):
            continue
        s = strip_comments(read(p))
        got = set()
        for pat in (r"\\newcommand\*?\{\\([A-Za-z]+)\}",
                    r"\\renewcommand\*?\{\\([A-Za-z]+)\}",
                    r"\\providecommand\*?\{\\([A-Za-z]+)\}",
                    r"\\DeclareRobustCommand\*?\{\\([A-Za-z]+)\}",
                    r"\\DeclareMathOperator\*?\{\\([A-Za-z]+)\}",
                    r"\\def\\([A-Za-z]+)"):
            got |= set(re.findall(pat, s))
        defs |= got
        if os.path.basename(p) in NUM_FILES:
            nums |= got
    return defs, nums


def referenced_macros():
    texts = [(os.path.join(PAPER, "main.tex"), read(os.path.join(PAPER, "main.tex")))]
    if os.path.isdir(TABDIR):
        for fn in sorted(os.listdir(TABDIR)):
            if fn.endswith(".tex"):
                p = os.path.join(TABDIR, fn)
                texts.append((p, read(p)))
    for extra in ("macros.tex",):
        p = os.path.join(PAPER, extra)
        if os.path.isfile(p):
            texts.append((p, read(p)))

    refs = {}
    for path, raw in texts:
        s = strip_comments(raw)
        # take only contiguous letters: in \approx0.3 the control sequence is
        # \approx, not \approx0
        for m in re.finditer(r"\\([A-Za-z]+)", s):
            name = m.group(1)
            if name in BUILTIN:
                continue
            refs.setdefault(name, set()).add(os.path.relpath(path, _ROOT))
    return refs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--strict", action="store_true")
    args = ap.parse_args()

    defs, nums = defined_macros()
    refs = referenced_macros()
    # Only definitions in numbers.tex count as "this number is actually used";
    # the hundreds of internal macros in the style files don't, otherwise the
    # dead-macro list would be all noise.
    used_by_paper = {k for k in refs if k in nums}
    missing = sorted(k for k in refs if k not in defs)
    dead = sorted(nums - used_by_paper)
    # macro names containing digits are illegal in LaTeX (control sequences may
    # only consist of letters)
    illegal = sorted(k for k in nums if not k.isalpha())

    print("defined in %s : %d" % ("+".join(NUM_FILES), len(nums)))
    print("defined anywhere       : %d" % len(defs))
    print("referenced (non-builtin): %d" % len(refs))
    print("matched                : %d" % len(used_by_paper))

    if illegal:
        print("\n[ILLEGAL] macro name contains digits -> \\newcommand causes a fatal error, entire build fails:")
        for k in illegal:
            print("   \\%s" % k)
    else:
        print("\n[ILLEGAL] none -- all macro names are pure letters")

    if missing:
        print("\n[MISSING] referenced but NOT defined -> pdflatex will error:")
        for k in missing:
            print("   \\%s   <- %s" % (k, ", ".join(sorted(refs[k]))))
    else:
        print("\n[MISSING] none -- all macros referenced in the body are defined")

    if dead:
        print("\n[DEAD] defined in the number-macro file but never referenced in the body (%d):" % len(dead))
        line = "   "
        for k in dead:
            if len(line) + len(k) > 96:
                print(line)
                line = "   "
            line += k + "  "
        if line.strip():
            print(line)

    if (missing or illegal) and args.strict:
        sys.exit(1)


if __name__ == "__main__":
    main()
